# -*- coding: utf-8 -*-
# Шаблон сторожа. Файлы guards/*.py, имя которых НЕ начинается с «_», зовёт checks.py,
# а checks.py зовёт deploy.ps1 перед каждой выкаткой. Этот файл не зовётся.
#
# Шапка (первые 15 строк, строки вида «# ключ: значение») читается checks.py:
#   # about: одна строка о том, что сторож стережёт (печатается в отчёте)
#   # needs-db            (без значения) сторож требует поднятой базы, пропускается с --quick
#   # cwd: frontend/src   каталог запуска относительно корня репозитория (по умолчанию корень)
#
# Порядок запуска идёт по имени файла: 10-..., 20-... (дешёвые первыми).
# Контракт, три исхода:
#   0  мера прошла;
#   3  мера не состоялась (нет базы, нет маркера, нечего сравнивать): строка «НЕ СОСТОЯЛАСЬ: причина».
#      Молчать по причине окружения и отвечать «ок» нельзя: такой сторож неотличим от зелёного;
#   1  мера не прошла: строки, которые начинаются с «ПЛОХО» или «ОТКАЗ». В отчёт попадут они,
#      а не хвост вывода.
# Сообщение называет то, что измерено («список пуст: 0 строк по условию X»), а не догадку
# о причине («сломан отбор»): пустота бывает правдой, и догадка отправит искать несуществующий дефект.
#
# about: пример: в репозитории нет файла STOP-DEPLOY
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent

if (ROOT / "STOP-DEPLOY").exists():
    print("ПЛОХО: в корне лежит STOP-DEPLOY, выкатка запрещена")
    sys.exit(1)
print("ок")
